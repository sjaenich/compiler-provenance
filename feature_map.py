# Strings you care about
TARGET_STRINGS = {"HTTP", "FTP", "LDAP", "DICT", "TELNET"}

def find_string_literals(node, active_macros=None):
    """Recursively walk the AST to find string literals under #ifdef/#ifndef guards."""
    results = []

    # # Handle conditional compilation nodes
    # if node.kind in (CursorKind.IFDEF, CursorKind.IFNDEF):
    #     macro = node.displayname
    #     negated = (node.kind == CursorKind.IFNDEF)
    #     new_active = (active_macros or []) + [(macro, negated)]
    #     for c in node.get_children():
    #         results.extend(find_string_literals(c, new_active))
    #     return results

    # String literal
    if node.kind == CursorKind.STRING_LITERAL:
        val = node.spelling.strip('"')
        print(val)
        if val in TARGET_STRINGS:
            results.append((val, active_macros or []))

    # Recurse
    for c in node.get_children():
        results.extend(find_string_literals(c, active_macros))
    return results


