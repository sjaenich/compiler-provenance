def main():
    # Load compile_commands.json (generated by cmake -DCMAKE_EXPORT_COMPILE_COMMANDS=ON)
    with open("compile_commands.json") as f:
        db = json.load(f)

    results = {}  # map: string → list of macros
    for entry in db:
        file_path = entry["file"]
        args = entry.get("arguments") or entry.get("command").split()

        # Remove compiler executable
        if args and not args[0].startswith("-"):
            args = args[1:]
        file_results = analyze_file("lib/ftp.c", args)
        break
        for string, macros in file_results:
            results.setdefault(string, set()).update(macros)

    # Print summary
    for string, macros in results.items():
        print(f"\nString '{string}' appears under:")
        for macro, neg in macros:
            print(f"   {'!' if neg else ''}{macro}")


if __name__ == "__main__":
    main()
